import { chromium } from '../.cache/pet-qa/node_modules/playwright/index.mjs';
import { createApp } from '../pet-app/server.mjs';
import { mkdtempSync, mkdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import assert from 'node:assert/strict';

const root = mkdtempSync(join(tmpdir(), 'dafeyu-browser-'));
const app = createApp({ dataDir: root, secureCookies: false, chat: { reply: async ({ text, memories }) => `我在呢。${memories.length ? '我记得：' + memories.join('，') + '。' : ''}你刚才说“${text}”，我们慢慢聊。` } });
await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
const base = `http://127.0.0.1:${app.server.address().port}`;
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
const page = await context.newPage(); const errors = [];
page.on('pageerror', error => errors.push(error.message));
try {
  const invite = app.store.createInvite({ admin: true });
  await page.goto(base + '/#invite=' + invite);
  await page.locator('#username').fill('qaowner'); await page.locator('#display-name').fill('小岛主人'); await page.locator('#password').fill('a browser test password 123');
  await page.locator('#auth-submit').click(); await page.locator('#chat-view').waitFor({ state: 'visible' });
  await page.locator('#pet-video').waitFor({ state: 'visible' });
  await page.waitForFunction(() => document.getElementById('pet-video').currentTime > 0, null, { timeout: 15000 });
  await page.locator('#open-actions').click(); assert.ok(await page.locator('#action-list button').count() > 100);
  await page.locator('#action-search').fill('吃白饭'); await page.locator('#action-list button').first().click();
  await page.waitForFunction(() => document.getElementById('pet-status').textContent.includes('吃白饭'));
  await page.locator('#close-actions').click();
  await page.locator('#sleep').click(); await page.waitForFunction(() => document.getElementById('pet-status').textContent === '睡觉中');
  await page.locator('#pet-touch').click(); await page.waitForFunction(() => document.getElementById('pet-status').textContent !== '睡觉中');
  await page.locator('#open-memory').click(); await page.locator('#memory-input').fill('我喜欢蓝莓'); await page.locator('#memory-form button').click();
  await page.getByText('我喜欢蓝莓', { exact: true }).waitFor(); await page.locator('#close-memory').click();
  await page.locator('#message-input').fill('今天想在这里歇一会儿'); await page.locator('#send').click();
  await page.waitForFunction(() => document.querySelector('#messages .assistant')?.textContent.includes('蓝莓'));
  await page.locator('#create-invite').click(); await page.locator('#invite-output').waitFor({ state: 'visible' }); const friendInvite = await page.locator('#invite-output').inputValue();
  mkdirSync(resolve('artifacts'), { recursive: true });
  await page.screenshot({ path: resolve('artifacts/dafeyu-pwa-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: resolve('artifacts/dafeyu-pwa-mobile.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.locator('#logout').click(); await page.locator('#auth-view').waitFor({ state: 'visible' });
  assert.equal(await page.locator('#messages').textContent(), '');
  await page.goto(friendInvite); await page.locator('#username').fill('qafriend'); await page.locator('#password').fill('another browser password 123');
  await page.locator('#auth-submit').click(); await page.locator('#chat-view').waitFor({ state: 'visible' });
  assert.ok(!(await page.locator('#messages').textContent()).includes('蓝莓'));
  await page.locator('#open-memory').click(); assert.ok(!(await page.locator('#memories').textContent()).includes('蓝莓'));
  await page.locator('#close-memory').click();
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  const keys = await page.evaluate(async () => { const out = []; for (const name of await caches.keys()) for (const req of await (await caches.open(name)).keys()) out.push(new URL(req.url).pathname); return out; });
  assert.equal(keys.some(path => path.startsWith('/api/')), false);
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log(JSON.stringify({ browser: 'installed Chrome, desktop and mobile viewport', registeredAccounts: 2, animationsPlaying: true, actions: 114, isolation: true, privateApiCached: false, pageErrors: errors, screenshots: ['artifacts/dafeyu-pwa-desktop.png', 'artifacts/dafeyu-pwa-mobile.png'] }));
} finally { await browser.close(); await app.close(); rmSync(root, { recursive: true, force: true }); }
